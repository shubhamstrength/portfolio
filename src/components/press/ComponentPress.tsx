import { useCallback, useEffect, useRef, type KeyboardEvent, type PointerEvent } from 'react'
import { follow, spring, useInView, useLoop, useReadout, type Spring } from '../iso/live'
import { APPS, FIRST_VERSION, nextVersion, readoutOf, STAMP, versionText, type Version } from './model'
import { ART, HEIGHT, move, needleAt, PZ_PRESS, PZ_REST, REACH, screenOf, WIDTH } from './geometry'
import '../iso/iso.css'
import './press.css'

const LABEL =
  'A component press. A gantry carries one shared die, the design system button, over six app sheets on a bed. ' +
  'The plunger presses the same button into each app in turn, a dial on the head reads the stroke, and a rack at the back holds the other component dies.'

const IDLE_RESUME = 3600
const SEATS = APPS.map((app) => screenOf([app.x, app.y, STAMP.z]))

interface State {
  bx: number
  hy: number
  pz: Spring
  goal: number
  press: boolean
  stamped: boolean[]
  alpha: number[]
  version: Version
  touring: boolean
  wait: number
}

const restingState = (): State => ({
  bx: APPS[0].x - REACH,
  hy: APPS[0].y,
  pz: { at: PZ_REST, rate: 0 },
  goal: 0,
  press: false,
  stamped: APPS.map(() => false),
  alpha: APPS.map(() => 0),
  version: FIRST_VERSION,
  touring: true,
  wait: 0,
})

const RESTING_READOUT = readoutOf(FIRST_VERSION, APPS.map(() => false), null)

// Static art is trusted markup generated by geometry.ts, so it is injected as-is.
const art = (markup: string) => ({ __html: markup })

export function ComponentPress() {
  const { anchor, say } = useReadout<HTMLDivElement>()
  const svg = useRef<SVGSVGElement>(null)
  const bridge = useRef<SVGGElement>(null)
  const head = useRef<SVGGElement>(null)
  const plunger = useRef<SVGGElement>(null)
  const needle = useRef<SVGPathElement>(null)
  const marks = useRef<(SVGGElement | null)[]>([])
  const state = useRef<State>(restingState())
  const idle = useRef(0)
  const visible = useInView(anchor)

  const describe = useCallback(() => {
    const s = state.current
    const done = s.stamped.filter(Boolean).length
    anchor.current?.setAttribute(
      'aria-valuetext',
      `${versionText(s.version)}: app ${s.goal + 1} selected, ${done} of ${APPS.length} apps stamped with the latest button`,
    )
    anchor.current?.setAttribute('aria-valuenow', String(s.goal + 1))
  }, [anchor])

  const release = useCallback(() => {
    const s = state.current
    s.version = nextVersion(s.version)
    s.stamped = APPS.map(() => false)
    s.wait = 0
    describe()
  }, [describe])

  const kick = useLoop((dt, calm) => {
    const s = state.current
    const tx = APPS[s.goal].x - REACH
    const ty = APPS[s.goal].y
    s.bx = follow(s.bx, tx, dt, 0.34, calm)
    s.hy = follow(s.hy, ty, dt, 0.28, calm)
    const arrived = Math.abs(s.bx - tx) < 0.25 && Math.abs(s.hy - ty) < 0.25

    // Critically damped stroke; the die stops dead on the sheet.
    const down = s.press && arrived
    spring(s.pz, down ? PZ_PRESS : PZ_REST, dt, down ? 220 : 120, down ? 2 * Math.sqrt(220) : 2 * Math.sqrt(120), calm)
    if (s.pz.at <= PZ_PRESS + 0.05) {
      s.pz.at = PZ_PRESS
      s.pz.rate = 0
      if (s.press) {
        s.press = false
        if (!s.stamped[s.goal]) {
          s.stamped[s.goal] = true
          describe()
        }
      }
    }

    let fading = false
    s.alpha = s.alpha.map((value, index) => {
      const next = follow(value, s.stamped[index] ? 1 : 0, dt, 0.1, calm)
      if (next !== (s.stamped[index] ? 1 : 0)) fading = true
      marks.current[index]?.setAttribute('opacity', next.toFixed(3))
      return next
    })

    const resting = !s.press && arrived && s.pz.at === PZ_REST
    if (s.touring && resting) {
      s.wait += dt
      const next = s.stamped.indexOf(false)
      if (next < 0 && s.wait > 1.8) release()
      else if (next >= 0 && s.wait > 0.5) {
        s.wait = 0
        s.goal = next
        s.press = true
        describe()
      }
    }

    bridge.current?.setAttribute('transform', move([s.bx, 0, 0]))
    head.current?.setAttribute('transform', move([0, s.hy, 0]))
    plunger.current?.setAttribute('transform', move([0, 0, s.pz.at]))
    needle.current?.setAttribute('d', needleAt(PZ_REST - s.pz.at))
    const stroke = s.pz.at < PZ_REST - 0.5
    say(readoutOf(s.version, s.stamped, s.press || stroke ? { app: s.goal, stroke } : null))

    return s.touring || !resting || fading
  }, visible)

  useEffect(() => {
    const calm = window.matchMedia('(prefers-reduced-motion: reduce)')
    if (calm.matches) state.current.touring = false
    return () => window.clearTimeout(idle.current)
  }, [])

  const steer = useCallback(
    (change: (s: State) => void) => {
      const s = state.current
      s.touring = false
      change(s)
      describe()
      window.clearTimeout(idle.current)
      idle.current = window.setTimeout(() => {
        if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return
        state.current.touring = true
        state.current.wait = 0
        kick()
      }, IDLE_RESUME)
      kick()
    },
    [describe, kick],
  )

  const seatUnder = (event: PointerEvent) => {
    const matrix = svg.current?.getScreenCTM()
    if (!matrix) return -1
    const point = new DOMPoint(event.clientX, event.clientY).matrixTransform(matrix.inverse())
    let best = -1
    let nearest = 46
    SEATS.forEach(([x, y], index) => {
      const distance = Math.hypot(point.x - x, point.y - y)
      if (distance < nearest) {
        nearest = distance
        best = index
      }
    })
    return best
  }

  const onPointerMove = (event: PointerEvent) => {
    if (event.pointerType !== 'mouse') return
    const seat = seatUnder(event)
    if (seat < 0 || seat === state.current.goal) return
    steer((s) => {
      s.goal = seat
      s.press = true
    })
  }

  const onPointerUp = (event: PointerEvent) => {
    const seat = seatUnder(event)
    if (event.pointerType !== 'mouse' && seat >= 0) {
      steer((s) => {
        s.goal = seat
        s.press = true
      })
      return
    }
    steer(() => release())
  }

  const onKeyDown = (event: KeyboardEvent) => {
    const { goal } = state.current
    const col = goal % 3
    const row = Math.floor(goal / 3)
    const moves: Record<string, number> = {
      ArrowLeft: row * 3 + Math.max(0, col - 1),
      ArrowRight: row * 3 + Math.min(2, col + 1),
      ArrowUp: col,
      ArrowDown: 3 + col,
      Home: 0,
      End: APPS.length - 1,
    }
    if (event.key in moves) {
      event.preventDefault()
      steer((s) => {
        s.goal = moves[event.key]
      })
    } else if (event.key === 'Enter' || event.key === ' ') {
      event.preventDefault()
      steer((s) => {
        s.press = true
      })
    } else if (event.key === 'r' || event.key === 'R') {
      event.preventDefault()
      steer(() => release())
    }
  }

  const rest = restingState()

  return (
    <figure className="iso press">
      <div className="iso-plate">
        <div className="iso-plate-corners" aria-hidden="true">
          <span className="iso-plate-corner" data-corner="fig">
            Fig 1
          </span>
          <span className="iso-plate-corner" data-corner="title">
            Component press
          </span>
          <span className="iso-plate-corner" data-corner="hint">
            <span className="press__hint--mouse">Hover to stamp · click to release</span>
            <span className="press__hint--touch">Tap an app to stamp it</span>
          </span>
          <span className="iso-plate-corner" data-corner="readout" data-readout="">
            {RESTING_READOUT}
          </span>
        </div>
        <div
          ref={anchor}
          className="iso-stage press__stage"
          tabIndex={0}
          role="slider"
          aria-label="Component press. Arrow keys pick an app, Enter stamps the shared button into it, R releases a new version."
          aria-valuemin={1}
          aria-valuemax={APPS.length}
          aria-valuenow={1}
          aria-valuetext={`${versionText(FIRST_VERSION)}: app 1 selected, 0 of ${APPS.length} apps stamped with the latest button`}
          onPointerMove={onPointerMove}
          onPointerUp={onPointerUp}
          onKeyDown={onKeyDown}
        >
          <svg ref={svg} className="iso-svg" viewBox={`0 0 ${WIDTH} ${HEIGHT}`} role="img" aria-label={LABEL} focusable="false">
            <g dangerouslySetInnerHTML={art(ART.base)} />
            {APPS.map((_, index) => (
              <g key={index}>
                <g dangerouslySetInnerHTML={art(ART.sheets[index])} />
                <g
                  ref={(node) => {
                    marks.current[index] = node
                  }}
                  opacity={0}
                  dangerouslySetInnerHTML={art(ART.marks[index])}
                />
              </g>
            ))}
            <g dangerouslySetInnerHTML={art(ART.nearRail)} />
            <g ref={bridge} transform={move([rest.bx, 0, 0])}>
              <g dangerouslySetInnerHTML={art(ART.legs)} />
              <g dangerouslySetInnerHTML={art(ART.beam)} />
              <g ref={head} transform={move([0, rest.hy, 0])}>
                <g ref={plunger} transform={move([0, 0, PZ_REST])} dangerouslySetInnerHTML={art(ART.plunger)} />
                <g dangerouslySetInnerHTML={art(ART.head)} />
                <path ref={needle} className="iso-line" data-tone="lit" data-free="start" d={needleAt(0)} style={{ strokeWidth: 1.1 }} />
              </g>
            </g>
            <g dangerouslySetInnerHTML={art(ART.console)} />
          </svg>
        </div>
      </div>
    </figure>
  )
}
