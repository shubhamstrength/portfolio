import { useEffect, useRef, type KeyboardEvent, type PointerEvent } from 'react'
import { spring, useInView, useLoop, useReadout, type Spring } from '../iso/live'
import { ROLES, readoutOf, tenureText } from './model'
import { ART, bodyAt, cardOpacity, DRAWERS, HEIGHT, move, OPEN, WIDTH } from './geometry'
import '../iso/iso.css'
import './cabinet.css'

const LABEL =
  'A card cabinet with one drawer per role, oldest at the bottom. Each drawer is as tall as the time spent in that role, ' +
  'a scale on the side counts the years, and the open drawer holds one index card per tool in that role’s stack.'

interface Props {
  selected: number
  onSelect: (index: number) => void
}

// Static art is trusted markup generated by geometry.ts, so it is injected as-is.
const art = (markup: string) => ({ __html: markup })

export function WorkCabinet({ selected, onSelect }: Props) {
  const { anchor, say } = useReadout<HTMLDivElement>()
  const fronts = useRef<(SVGGElement | null)[]>([])
  const bodies = useRef<(SVGGElement | null)[]>([])
  const drawers = useRef<Spring[]>(DRAWERS.map(() => ({ at: 0, rate: 0 })))
  const target = useRef(selected)
  const selectedRef = useRef(selected)
  const visible = useInView(anchor)

  const draw = (index: number) => {
    const open = drawers.current[index].at
    const group = fronts.current[index]
    if (!group) return
    group.setAttribute('transform', move([open, 0, 0]))
    group.querySelectorAll<SVGGElement>('[data-card]').forEach((card) => {
      card.setAttribute('opacity', cardOpacity(Number(card.dataset.card), open).toFixed(3))
    })
    const body = bodies.current[index]
    if (body) body.innerHTML = bodyAt(index, open)
  }

  const kick = useLoop((dt, calm) => {
    let settled = true
    drawers.current.forEach((state, index) => {
      const goal = index === target.current ? OPEN : 0
      if (state.at === goal && state.rate === 0) return
      // A heavy drawer on runners: slightly underdamped going out, firm coming home.
      settled = spring(state, goal, dt, goal ? 90 : 140, goal ? 15 : 24, calm) && settled
      state.at = Math.max(0, state.at)
      draw(index)
    })
    return !settled
  }, visible)

  useEffect(() => {
    target.current = selected
    selectedRef.current = selected
    fronts.current.forEach((group, index) => {
      group?.querySelector('[data-front] > .iso-solid')?.toggleAttribute('data-lit', index === selected)
    })
    say(readoutOf(selected))
    kick()
  }, [selected, say, kick])

  useEffect(() => {
    DRAWERS.forEach((_, index) => draw(index))
    // draw only reads refs; run once to paint the resting pose.
  }, []) // eslint-disable-line react-hooks/exhaustive-deps

  const choose = (index: number) => {
    if (index !== selectedRef.current) onSelect(index)
  }

  const drawerUnder = (event: PointerEvent) => {
    const hit = (event.target as Element).closest('[data-drawer]')
    return hit ? Number((hit as HTMLElement).dataset.drawer) : -1
  }

  const onPointerMove = (event: PointerEvent) => {
    if (event.pointerType !== 'mouse') return
    const index = drawerUnder(event)
    if (index >= 0) choose(index)
  }

  const onPointerUp = (event: PointerEvent) => {
    const index = drawerUnder(event)
    if (index >= 0) choose(index)
  }

  const onKeyDown = (event: KeyboardEvent) => {
    const steps: Record<string, number> = {
      ArrowUp: Math.min(ROLES.length - 1, selected + 1),
      ArrowRight: Math.min(ROLES.length - 1, selected + 1),
      ArrowDown: Math.max(0, selected - 1),
      ArrowLeft: Math.max(0, selected - 1),
      Home: ROLES.length - 1,
      End: 0,
    }
    if (!(event.key in steps)) return
    event.preventDefault()
    choose(steps[event.key])
  }

  const { role, months } = ROLES[selected]

  return (
    <div className="iso cabinet">
      <div className="iso-plate cabinet__plate">
        <div
          ref={anchor}
          className="iso-stage cabinet__stage"
          tabIndex={0}
          role="slider"
          aria-label="Career cabinet. Arrow keys open the drawer for the next or previous role."
          aria-valuemin={1}
          aria-valuemax={ROLES.length}
          aria-valuenow={selected + 1}
          aria-valuetext={`${role.company}, ${tenureText(months)}, ${role.stack.length} tools`}
          onPointerMove={onPointerMove}
          onPointerUp={onPointerUp}
          onKeyDown={onKeyDown}
        >
          <svg className="iso-svg" viewBox={`0 0 ${WIDTH} ${HEIGHT}`} role="img" aria-label={LABEL} focusable="false">
            <g dangerouslySetInnerHTML={art(ART.base)} />
            {DRAWERS.map((_, index) => (
              <g key={index} data-drawer={index}>
                <g
                  ref={(node) => {
                    bodies.current[index] = node
                  }}
                />
                <g
                  ref={(node) => {
                    fronts.current[index] = node
                  }}
                  dangerouslySetInnerHTML={art(ART.fronts[index])}
                />
              </g>
            ))}
          </svg>
        </div>
        <div className="cabinet__footer mono" aria-hidden="true">
          <span>
            <span className="cabinet__hint--mouse">Hover a drawer to open it</span>
            <span className="cabinet__hint--touch">Tap a drawer to open it</span>
          </span>
          <span data-readout="">{readoutOf(selected)}</span>
        </div>
      </div>
    </div>
  )
}
